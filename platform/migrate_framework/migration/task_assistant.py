def _proposal_unified_api(project: MigrationProject, task: dict[str, Any], phase: dict[str, Any]) -> dict[str, Any]:
    base = _base_dir(project, task)
    context_name = phase.get("name") or "Bounded Context"
    paths = "\n".join(
        f"  /legacy/{service.replace('-service', '')}/{{id}}:\n"
        f"    get:\n"
        f"      summary: Strangler route to legacy {service}\n"
        f"      responses:\n"
        f"        '200':\n"
        f"          description: Proxied legacy response\n"
        for service in (phase.get("services") or [])[:5]
    )
    openapi = f"""openapi: 3.0.3
info:
  title: {context_name} Unified API (draft)
  version: 0.1.0-draft
paths:
{paths}
  /health:
    get:
      summary: Health
      responses:
        '200':
          description: OK
"""

    files = [_file_proposal(project, f"{base}/openapi.yaml", openapi, action="modify")]

    return {
        "proposal_id": new_id("proposal"),
        "task_id": task.get("id"),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "guidance": "Unified API draft with strangler routes to legacy services. Review before publishing.",
        "files": files,
    }


def assist_playbook_task(project: MigrationProject, task: dict[str, Any]) -> dict[str, Any]:
    """Generate guidance and reviewable file proposals for a playbook task."""
    phase = _phase_for_task(project, task)
    text = (task.get("task") or "").lower()

    if "scaffold" in text:
        return _proposal_scaffold(project, task, phase)
    if "anti-corruption" in text or "anti corruption" in text:
        return _proposal_acl(project, task, phase)
    if "schema migration" in text or "migration script" in text:
        return _proposal_schema_migration(project, task, phase)
    if "contract test" in text:
        return _proposal_contract_tests(project, task, phase)
    if "aggregate root" in text:
        return _proposal_aggregate_roots(project, task, phase)
    if "unified api" in text:
        return _proposal_unified_api(project, task, phase)

    return _guidance_only(task, phase)


def get_playbook_tasks(project: MigrationProject) -> list[dict[str, Any]]:
    return list(project.metadata.get("playbook") or [])


def update_task_status(project: MigrationProject, task_id: str, status: str) -> None:
    for task in get_playbook_tasks(project):
        if task.get("id") == task_id:
            task["status"] = status
            break
    project.metadata["playbook"] = get_playbook_tasks(project)


def store_proposal(project: MigrationProject, proposal: dict[str, Any]) -> None:
    proposals = project.metadata.setdefault("playbook_proposals", {})
    proposals[proposal["task_id"]] = proposal


def get_proposal(project: MigrationProject, task_id: str) -> dict[str, Any] | None:
    return project.metadata.get("playbook_proposals", {}).get(task_id)


def apply_proposal_files(
    project: MigrationProject,
    proposal: dict[str, Any],
    selected_paths: set[str],
) -> list[str]:
    """Apply approved files from a proposal. Returns list of written paths."""
    source_root = project.repo_root()
    written: list[str] = []

    for file_entry in proposal.get("files") or []:
        path = file_entry.get("path", "")
        if path not in selected_paths:
            continue
        full_path = source_root / path
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_text(file_entry.get("content", ""), encoding="utf-8")
        written.append(path)

    return written
